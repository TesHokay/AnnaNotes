/**
 * Hand-authored centre-line trajectories for the launch animation (original work, no font data).
 *
 * Latin/Cyrillic glyphs: units where the x-height is 1, the baseline is y = 0 and y grows
 * downwards (x-height line at y = -1, ascenders ≈ -2.2, descenders ≈ +1.2). Points are where the
 * pen passes; a Catmull-Rom spline makes the curve. Letters inside a word are joined into one
 * continuous stroke, like real cursive writing.
 *
 * Chinese glyphs: a 1×1 box per character; each stroke in the correct stroke order, with a
 * pressure profile for brush rendering.
 */

export type Pt = [number, number];

export interface Glyph {
  adv: number;
  strokes: Pt[][];
  /** The letter ends at the x-height (o, v, b, ю): the next letter is joined at the top. */
  exitTop?: boolean;
  /** Never join this glyph to its neighbours (capitals with separate swashes, apostrophe). */
  isolated?: boolean;
  /** The pen lifts before this glyph (it starts high, e.g. б). */
  breakBefore?: boolean;
  /** The pen lifts after this glyph (it ends high, e.g. б); the next letter starts a new stroke. */
  breakAfter?: boolean;
}

